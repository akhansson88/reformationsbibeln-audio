const fs = require("node:fs"), path = require("node:path"), books = require("../lib/books.js");
const root = path.resolve(__dirname, "..", "firebase");
fs.mkdirSync(root, { recursive: true });
// Explicit chapter tables avoid constructing all 1189 counts for every request.
const verseCounts = books.map((b, i) => `${i ? "        " : "      return "}${i < books.length - 1 ? `book == ${b.id} ? ` : ""}${JSON.stringify(b.verses)}[chapter - 1]${i < books.length - 1 ? " :" : ";"}`).join("\n");
const fields = ["schemaVersion", "source", "extensionVersion", "clientReportId", "translation", "bookId", "bookName", "chapter", "verse", "verseText", "selectedWords", "description", "audioRevision", "audioUrl", "audioChecksum", "status", "reporterUid", "createdAt"];
// Match JavaScript trim/whitespace, including Swedish non-breaking spaces.
const whitespace = "\\\\t\\\\r\\\\n\\\\f\\\\v "+"\u0085\u00a0\u1680\u2000-\u200a\u2028\u2029\u202f\u205f\u3000\ufeff";
const rules = `// Generated by scripts/build-firestore-rules.cjs. Deploy this native rules file.
rules_version = '2';
service cloud.firestore {
  match /databases/{database}/documents {
    function anonymous() {
      return request.auth != null && request.auth.token.firebase.sign_in_provider == 'anonymous';
    }
    function ownId(id) {
      return anonymous() && id.matches(request.auth.uid + '_[a-f0-9]{8}-[a-f0-9]{4}-4[a-f0-9]{3}-[89ab][a-f0-9]{3}-[a-f0-9]{12}');
    }
    function verseCount(book, chapter) {
${verseCounts}
    }
    function validReference(d) {
      let chapters = ${JSON.stringify(books.map(b => b.verses.length))};
      let names = ${JSON.stringify(books.map(b => b.name))};
      return d.bookId is int && d.bookId >= 1 && d.bookId <= 66 &&
        d.bookName is string && d.bookName == names[d.bookId - 1] &&
        d.chapter is int && d.chapter >= 1 && d.chapter <= chapters[d.bookId - 1] &&
        d.verse is int && d.verse >= 1 && d.verse <= verseCount(d.bookId, d.chapter);
    }
    function nonBlank(value) {
      return value.matches('(?s).*[^${whitespace}].*');
    }
    function validWords(d) {
      let tokens = d.verseText.split(' ');
      let selected = d.selectedWords;
      return d.verseText is string && d.verseText.size() <= 6000 &&
        d.verseText.matches('([^${whitespace}]+( [^${whitespace}]+)*)?') &&
        selected is map && selected.size() <= 1000 &&
        (selected.size() == 0 || (d.verseText.size() > 0 &&
          selected.size() <= tokens.size() &&
          selected.keys().join(',').matches('(0|[1-9][0-9]{0,2})(,(0|[1-9][0-9]{0,2}))*') &&
          selected.values().toSet().hasOnly(tokens.toSet()))) &&
        d.description is string && d.description.size() <= 1000 &&
        (selected.size() > 0 || nonBlank(d.description));
    }
    function validAudio(d) {
      return d.audioRevision is string && d.audioRevision.matches('[A-Za-z0-9_-]{1,80}') &&
        d.audioChecksum is string && d.audioChecksum.matches('[a-f0-9]{64}') &&
        d.audioUrl is string && d.audioUrl.size() <= 400 &&
        d.audioUrl == 'https://github.com/akhansson88/reformationsbibeln-audio/releases/download/audio-' +
          (d.bookId < 10 ? '0' : '') + string(d.bookId) + '-' + pad3(d.chapter) + '-' + d.audioRevision +
          '/verse-' + pad3(d.verse) + '.mp3';
    }
    function pad3(value) {
      return (value < 10 ? '00' : value < 100 ? '0' : '') + string(value);
    }
    function validReport(d, id) {
      let fields = ${JSON.stringify(fields)};
      return d.keys().hasAll(fields) && d.keys().hasOnly(fields) &&
        d.schemaVersion == 1 && d.source == 'chrome-extension' &&
        d.extensionVersion is string && d.extensionVersion.matches('[0-9]{1,3}[.][0-9]{1,3}[.][0-9]{1,3}') &&
        d.clientReportId is string && id == request.auth.uid + '_' + d.clientReportId &&
        d.translation == 'reformationsbibeln2026' && d.status == 'new' &&
        d.reporterUid == request.auth.uid && d.createdAt == request.time &&
        validReference(d) && validWords(d) && validAudio(d);
    }
    match /pronunciationReports/{reportId} {
      allow create: if ownId(reportId) && validReport(request.resource.data, reportId);
      // Only an exact receipt belonging to this anonymous user can be read.
      // No listing, edits or deletion. Firebase Console uses administrator IAM.
      allow get: if ownId(reportId);
      allow list, update, delete: if false;
    }
    match /{document=**} {
      allow read, write: if false;
    }
  }
}
`;
fs.writeFileSync(path.join(root, "firestore.rules"), rules);
fs.writeFileSync(path.join(root, "firestore-rules.json"), JSON.stringify({
  projectId: "reformationsbibeln-fel", format: "cloud-firestore-security-rules", deployFile: "firestore.rules", rules
}, null, 2) + "\n");
